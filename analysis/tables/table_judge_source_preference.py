"""LaTeX tables of source-associated LLM-as-a-judge behaviour.

See :mod:`fraudbench.analysis.table.judge_source_preference` for the
underlying implementation. This script is a thin CLI wrapper that emits up to
three tables, each grouping judge votes by whether the evaluated response was
generated by the exact judge model, by another model from the judge's family,
or by a model from another family:

* ``judge_source_preference.tex`` -- raw positive-label rates plus each
  judge's vote relative to the other two judges on the same completion, with
  the exact-self and family excess contrasts.
* ``judge_source_dissent.tex`` -- leave-one-judge-out lone-vote rates.
* ``judge_source_preference_by_task.tex`` -- the excess contrasts by task.

Usage:
    uv run analysis/tables/table_judge_source_preference.py
    uv run analysis/tables/table_judge_source_preference.py --no-save
    uv run analysis/tables/table_judge_source_preference.py --table main

    # Add case-clustered bootstrap 95% intervals to every estimate.
    uv run analysis/tables/table_judge_source_preference.py \\
        --bootstrap --bootstrap-resamples 2000 --seed 0

    uv run analysis/tables/table_judge_source_preference.py \\
        --input data/final/obs_data_per_score.parquet \\
        --output-dir paper/tables \\
        --run-category all
"""
from pathlib import Path

from jsonargparse import ArgumentParser

from fraudbench.analysis.table.judge_source_preference import (
    DEFAULT_BOOTSTRAP_RESAMPLES,
    DEFAULT_SEED,
    METRICS,
    RUN_CATEGORY_CHOICES,
    TABLES,
    run,
)
from fraudbench.analysis.uncertainty import DEFAULT_HDI_PROB


SCRIPT_DIR = Path(__file__).parent
_REPO_ROOT = SCRIPT_DIR.parent.parent
DEFAULT_OUTPUT_DIR = _REPO_ROOT / "paper" / "tables"


def main() -> None:
    """CLI entry point: parse args and dispatch to ``judge_source_preference.run``."""
    parser = ArgumentParser(
        description=(
            "Generate LaTeX tables of how each LLM judge labels responses "
            "generated by itself, by its own model family, and by other "
            "families, relative to the other two judges on the same responses."
        )
    )
    parser.add_argument(
        "--input", "-i", type=str,
        default="data/final/obs_data_per_score.parquet",
        help="Kept per-score observations (.parquet/.csv/.jsonl).",
    )
    parser.add_argument(
        "--output-dir", "-o", type=str,
        default=str(DEFAULT_OUTPUT_DIR),
        help=f"Output directory for the .tex files (default: {DEFAULT_OUTPUT_DIR}).",
    )
    parser.add_argument(
        "--table", "-t", choices=[*TABLES, "all"], default="all",
        help="Restrict output to a single table (default: all three).",
    )
    parser.add_argument(
        "--metric", "-m", choices=[*METRICS, "all"], default="all",
        help="Restrict the panels to a single metric (default: both).",
    )
    parser.add_argument(
        "--run-category", choices=list(RUN_CATEGORY_CHOICES), default="main",
        help="Restrict to main runs (default) or pool in the ablation runs.",
    )
    parser.add_argument(
        "--bootstrap", action="store_true",
        help="Add case-clustered bootstrap intervals under every estimate.",
    )
    parser.add_argument(
        "--bootstrap-resamples", type=int, default=DEFAULT_BOOTSTRAP_RESAMPLES,
        help=f"Bootstrap resamples (default: {DEFAULT_BOOTSTRAP_RESAMPLES}).",
    )
    parser.add_argument(
        "--seed", type=int, default=DEFAULT_SEED,
        help=f"Seed for the bootstrap resampling (default: {DEFAULT_SEED}).",
    )
    parser.add_argument(
        "--interval-prob", type=float, default=DEFAULT_HDI_PROB,
        help=f"Bootstrap interval probability mass (default: {DEFAULT_HDI_PROB:g}).",
    )
    parser.add_argument(
        "--no-save", action="store_true",
        help="Do not write files; print each table to stdout instead.",
    )
    args = parser.parse_args()

    run(
        input_path=args.input,
        output_dir=args.output_dir,
        metrics=list(METRICS) if args.metric == "all" else [args.metric],
        tables=list(TABLES) if args.table == "all" else [args.table],
        run_category=args.run_category,
        bootstrap=args.bootstrap,
        bootstrap_resamples=args.bootstrap_resamples,
        seed=args.seed,
        interval_prob=args.interval_prob,
        no_save=args.no_save,
    )


if __name__ == "__main__":
    main()
